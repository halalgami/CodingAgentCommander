package count

import (
	"strings"
	"testing"
)

func TestGoCounting(t *testing.T) {
	src := "package main\n\n// TODO: tidy\nfunc f(a, b bool) {\n\ts := \"// not a comment && ||\"\n\tif a && b || !a { /* block\n still comment FIXME */\n\t}\n\tfor i := 0; i < 3; i++ {}\n}\n"
	st := Count("x/main.go", []byte(src))
	if st.Lang != "go" || st.Excluded || st.Test {
		t.Fatalf("meta %+v", st)
	}
	if st.Code != 7 || st.Comment != 2 || st.Blank != 1 {
		t.Fatalf("lines code=%d comment=%d blank=%d (want 7/2/1)", st.Code, st.Comment, st.Blank)
	}
	// 1 + if + && + || + for ; the string's && || do not count
	if st.Complexity != 5 {
		t.Fatalf("complexity %d want 5", st.Complexity)
	}
	if st.Todos != 2 {
		t.Fatalf("todos %d want 2 (TODO + FIXME, both in comments)", st.Todos)
	}
}

func TestPythonAndShell(t *testing.T) {
	py := Count("a.py", []byte("# FIXME\nif x and y:\n    pass\nelif z or w:\n    pass\n"))
	if py.Lang != "python" || py.Comment != 1 || py.Code != 4 || py.Complexity != 5 || py.Todos != 1 {
		t.Fatalf("python %+v", py)
	}
	sh := Count("run.sh", []byte("#!/bin/sh\nif [ -n \"$X\" ]; then echo '#x'; fi\n"))
	if sh.Lang != "shell" || sh.Complexity != 2 || sh.Code != 1 || sh.Comment != 1 {
		t.Fatalf("shell %+v", sh)
	}
}

func TestTestPathsAndExclusions(t *testing.T) {
	for _, p := range []string{"a_test.go", "web/x.test.ts", "web/x.spec.js", "test_a.py", "pkg/a_test.py", "src/__tests__/a.js", "tests/helper.go"} {
		if !Count(p, []byte("x\n")).Test {
			t.Errorf("%s not detected as test", p)
		}
	}
	for _, p := range []string{"package-lock.json", "go.sum", "web/app.min.js", "yarn.lock"} {
		if !Count(p, []byte("x\n")).Excluded {
			t.Errorf("%s not excluded", p)
		}
	}
	if !Count("gen.go", []byte("// Code generated by x. DO NOT EDIT.\npackage x\n")).Excluded {
		t.Error("generated file not excluded")
	}
	if !Count("blob.bin.go", []byte("ab\x00cd")).Excluded {
		t.Error("binary not excluded")
	}
}

func TestUnknownLanguageCountsLinesOnly(t *testing.T) {
	st := Count("notes.xyz", []byte("a\n\nb\n"))
	if st.Lang != "other" || st.Code != 2 || st.Blank != 1 || st.Complexity != 1 {
		t.Fatalf("%+v", st)
	}
}

func FuzzCountLinesAddUp(f *testing.F) {
	f.Add("main.go", "a\n/* b\n\nc */ d\n\"//\"\n")
	f.Add("a.py", "#x\n'''y\n")
	f.Fuzz(func(t *testing.T, name, src string) {
		st := Count(name, []byte(src))
		if st.Excluded {
			return
		}
		lines := strings.Count(src, "\n")
		if src != "" && !strings.HasSuffix(src, "\n") {
			lines++
		}
		if st.Code+st.Comment+st.Blank != lines {
			t.Fatalf("%d+%d+%d != %d lines", st.Code, st.Comment, st.Blank, lines)
		}
	})
}
